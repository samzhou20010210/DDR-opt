#!/usr/bin/env python3
"""Generate DDR-opt's per-node parameter files from config/pool_rescue.yaml.

Legacy DDR-opt nodes read flat keys from their own private namespace (and mpc_controller
reads the hard-coded absolute namespace /mpc/...). This script is the only place that maps
the central, annotated pool parameters onto those keys, including derived values.

  python3 gen_ddr_params.py            # write config/generated/<mode>/<node>.yaml
  python3 gen_ddr_params.py --check    # exit 1 if the committed files are out of date
"""
import argparse
import json
import os
import sys

import yaml

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CENTRAL = os.path.join(PKG, "config", "pool_rescue.yaml")
OUT_DIR = os.path.join(PKG, "config", "generated")
MODES = ("approach", "rescue")
HEADER = ("# GENERATED by pool_rescue/scripts/gen_ddr_params.py from config/pool_rescue.yaml "
          "(mode: {mode}). DO NOT EDIT.\n# Loaded after the stock DDR-opt yaml inside node '{node}', "
          "so these keys override the stock values.\n")


def load_central(path=CENTRAL):
    with open(path) as f:
        return yaml.safe_load(f)


def v(cfg, dotted):
    """Value of a {value, unit, source} leaf addressed as 'a.b.c'."""
    node = cfg
    for k in dotted.split("."):
        node = node[k]
    return node["value"]


def r(x):
    """Round floats so generated files are stable and readable."""
    return round(float(x), 6)


def footprint_checkpoints(length, width):
    """Body-frame collision points: 4 corners + 4 edge midpoints, flattened [x0, y0, x1, y1, ...]."""
    hl, hw = length / 2.0, width / 2.0
    pts = [(hl, hw), (hl, 0.0), (hl, -hw), (0.0, -hw), (-hl, -hw), (-hl, 0.0), (-hl, hw), (0.0, hw)]
    return [r(c) for p in pts for c in p]


def pool_walls(L, W, t):
    """Four wall boxes [cx, cy, sx, sy, yaw] centred on the pool edges (map_box format).
    Replaces global_map_node's built-in boundary walls, which swap the x/y extents on
    non-square maps (see DEVLOG)."""
    return [r(x) for x in (
        0.0,     W / 2.0, t, W + t, 0.0,    # x = 0 wall
        L,       W / 2.0, t, W + t, 0.0,    # x = L wall
        L / 2.0, 0.0,     L + t, t, 0.0,    # y = 0 wall
        L / 2.0, W,       L + t, t, 0.0,    # y = W wall
    )]


def build(cfg, mode):
    m = "modes." + mode
    L, W = v(cfg, "pool.length"), v(cfg, "pool.width")
    res = v(cfg, "pool.map_resolution")
    vl, vw = v(cfg, "vessel.length"), v(cfg, "vessel.width")
    clear = v(cfg, "safety.wall_clearance")
    half_sep = v(cfg, "vessel.thruster_separation") / 2.0
    det = v(cfg, "sensing.detection_range")
    persp = bool(v(cfg, "sensing.perspective"))
    start = [r(v(cfg, "standby." + k)) for k in ("x", "y", "yaw")]

    limits = {
        "max_vel": r(v(cfg, m + ".max_forward_speed")),
        "min_vel": r(-v(cfg, m + ".max_reverse_speed")) if v(cfg, "vessel.reverse_enabled") else 0.0,
        # DDR-opt has a single symmetric acceleration limit -> take the tighter one.
        "max_acc": r(min(v(cfg, m + ".max_acceleration"), v(cfg, m + ".max_deceleration"))),
        "max_omega": r(v(cfg, m + ".max_yaw_rate")),
        "max_domega": r(v(cfg, m + ".max_yaw_accel")),
        "max_centripetal_acc": r(v(cfg, m + ".max_centripetal_acc")),
        "if_directly_constrain_v_omega": not bool(v(cfg, "vessel.couple_speed_and_turn_limits")),
    }
    icr = {"ICR_yl": r(half_sep), "ICR_yr": r(-half_sep), "ICR_xv": 0.0, "if_standard_diff": True}

    dt = v(cfg, "control.mpc_dt")
    delay_num = int(round(v(cfg, "control.latency") / dt))

    nodes = {}
    nodes["global_planning"] = dict(limits, **icr, **{
        "checkpoint": footprint_checkpoints(vl, vw),
        "safeDis": r(clear),
        # JPS plans for the centre point: inflate by half the beam + clearance.
        "jps_safe_dis": r(vw / 2.0 + clear),
        # check_final_collision() only checks the centre point.
        "finalMinSafeDis": r(vw / 2.0),
        "replan_time": r(v(cfg, "control.replan_period")),
        "max_replan_time": r(v(cfg, "control.max_replan_time")),
        "if_fix_final": False,
        "gridmap_interval": r(res),
        "detection_range": r(det),
        "global_x_lower": 0.0, "global_x_upper": r(L),
        "global_y_lower": 0.0, "global_y_upper": r(W),
        "if_perspective": persp,
        "if_cirSupRaycast": False,
        "hrz_limited": False,
    })
    nodes["simulator"] = dict(limits, **{
        "start_x": start[0], "start_y": start[1], "start_yaw": start[2],
        "length": r(vl), "width": r(vw), "height": r(v(cfg, "vessel.height")),
        "if_add_noise": bool(v(cfg, "simulation.add_noise")),
        "noise_stddev": r(v(cfg, "simulation.noise_stddev")),
        "State_Propa_rate": 500, "Pose_pub_rate": 100, "Pose_odom_pub_rate": 10,
        "detection_range": r(det), "hrz_limited": False,
        "ICR_yl": icr["ICR_yl"], "ICR_yr": icr["ICR_yr"], "ICR_xv": icr["ICR_xv"],
    })
    # mpc_controller reads ONLY absolute /mpc/<key>: this file must be loaded in a node named "mpc".
    nodes["mpc"] = dict(limits, **{
        "dt": r(dt),
        "cmd_timer_rate": r(v(cfg, "control.rate")),
        "delay_num": delay_num,
        "if_mpc": True,
    })
    nodes["global_map_node"] = {
        "Map_input_method": 1,
        "if_boundary_wall_": False,   # real key name (launch files set 'if_boundary_wall', which is ignored)
        "gridmap_interval": r(res),
        "laser_gridmap_interval": r(res),
        "map_size": [0.0, r(L), 0.0, r(W)],
        "map_box": pool_walls(L, W, v(cfg, "pool.wall_thickness_in_map")),
        "start_x": start[0], "start_y": start[1], "start_yaw": start[2],
    }
    nodes["laser_simulator"] = {
        "if_perspective": persp, "pc_resolution": r(res), "sensing_horizon": r(det), "hrz_limited": False,
    }
    nodes["icrekf"] = {
        "yr_standard": icr["ICR_yr"], "yl_standard": icr["ICR_yl"], "xv_standard": 0.0,
        "init_x_yr": icr["ICR_yr"], "init_x_yl": icr["ICR_yl"], "init_x_xv": 0.0,
    }
    nodes["ddr_adapter"] = {
        "latency": r(v(cfg, "control.latency")),
        "world_frame": v(cfg, "frames.world"),
        "base_frame": v(cfg, "frames.base_link"),
    }
    return nodes


def render(mode, node, params):
    # one key per line (lists stay inline) -> stable, diff-friendly files
    # (JSON scalars/lists are valid YAML)
    body = "".join("{}: {}\n".format(k, json.dumps(params[k])) for k in sorted(params))
    return HEADER.format(mode=mode, node=node) + body


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only verify generated files are up to date")
    a = ap.parse_args()
    cfg = load_central()
    stale = []
    for mode in MODES:
        os.makedirs(os.path.join(OUT_DIR, mode), exist_ok=True)
        for node, params in build(cfg, mode).items():
            path = os.path.join(OUT_DIR, mode, node + ".yaml")
            text = render(mode, node, params)
            old = open(path).read() if os.path.exists(path) else None
            if old != text:
                if a.check:
                    stale.append(path)
                else:
                    with open(path, "w") as f:
                        f.write(text)
                    print("wrote", os.path.relpath(path, PKG))
    if a.check:
        if stale:
            print("OUT OF DATE (run gen_ddr_params.py):", *stale, sep="\n  ")
            sys.exit(1)
        print("generated files up to date")


if __name__ == "__main__":
    main()
